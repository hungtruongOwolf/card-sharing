//! T-60: card `style` blocks validated against the registry exported by
//! `packages/effects-registry` (SR-28). No card route exists yet (the `POST /v1/cards` ticket will call
//! `AppState::validate_style`), so a test-only route exercises the helper end to end.

use crate::common::*;
use api::access::{RoutePolicy, ValidJson};
use api::state::AppState;
use axum::Json;
use axum::extract::State;
use http::StatusCode;
use platform::problem::ApiError;
use serde::Deserialize;
use serde_json::{Value, json};
use utoipa::ToSchema;
use utoipa_axum::routes;

#[derive(Debug, Deserialize, ToSchema)]
#[serde(deny_unknown_fields)]
struct StyleBody {
    #[schema(value_type = Object)]
    style: Value,
}

#[utoipa::path(post, path = "/test/style", responses((status = OK, description = "ok")))]
async fn style_route(
    State(state): State<AppState>,
    body: ValidJson<StyleBody>,
) -> Result<Json<Value>, ApiError> {
    Ok(Json(state.validate_style(&body.0.style)?))
}

fn app() -> axum::Router {
    api::build(
        api::openapi::router().route(RoutePolicy::public(), routes!(style_route)),
        offline_state(),
        &test_config(),
    )
}

#[tokio::test]
async fn a_valid_style_is_accepted_and_normalized() {
    let style = json!({
        "cut": { "id": "cut.diecut", "version": 1, "params": { "borderWidthPct": 2.5 } },
        "finish": { "id": "fx.holo", "version": 1 },
    });
    let response = send(
        &app(),
        post_json("/test/style", None, &json!({ "style": style })),
    )
    .await;
    assert_eq!(response.status(), StatusCode::OK);
    let body = json_body(response).await;
    assert_eq!(body["cut"]["params"]["borderWidthPct"], 2.5);
    assert_eq!(
        body["finish"]["params"]["intensity"], 0.8,
        "defaults filled in"
    );
}

#[tokio::test]
async fn unknown_ids_and_out_of_range_params_get_a_generic_422() {
    let mut bodies = Vec::new();
    for style in [
        json!({ "effects": [{ "id": "fx.unknown", "version": 1 }] }),
        json!({ "cut": { "id": "cut.diecut", "version": 1, "params": { "borderWidthPct": 1e308 } } }),
        json!({ "cut": { "id": "cut.diecut", "version": 9 } }),
    ] {
        let response = send(
            &app(),
            post_json("/test/style", None, &json!({ "style": style })),
        )
        .await;
        let mut body = assert_problem(
            response,
            StatusCode::UNPROCESSABLE_ENTITY,
            "UNKNOWN_REGISTRY_ID",
        )
        .await;
        assert!(body.get("detail").is_none(), "no hint which part failed");
        body.as_object_mut().unwrap().remove("requestId");
        bodies.push(body);
    }
    assert!(bodies.windows(2).all(|w| w[0] == w[1]));
}

#[test]
fn the_api_embeds_the_committed_registry_export() {
    // The export is generated by packages/effects-registry (a JS test fails CI when it is stale);
    // the API must load exactly that file.
    let registry = registry::Registry::embedded().unwrap();
    let export: Value = serde_json::from_str(registry::REGISTRY_JSON).unwrap();
    let ids = export["entries"].as_array().unwrap();
    assert_eq!(registry.len(), ids.len());
    for entry in ids {
        assert!(registry.get(entry["id"].as_str().unwrap()).is_some());
    }
}
